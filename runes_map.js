window.decodeRunePayload = function (p) {
  if (!p) return null;
  p = String(p);
  if (p.charAt(0) !== "r" || p.indexOf("x") < 0) return null;
  var parts = p.slice(1).split("-");
  var aminos = [];
  var images = [];
  for (var i = 0; i < parts.length; i++) {
    var m = parts[i].match(/^(\d+)x(\d+)$/);
    if (!m) continue;
    var name = window.RUNE_AMINO_ORDER[parseInt(m[1], 10)];
    if (!name) continue;
    var files = window.RUNE_IMAGES[name] || [];
    var ii = parseInt(m[2], 10);
    aminos.push(name);
    images.push(files[ii] || files[0] || (name + ".jpg"));
  }
  if (!aminos.length) return null;
  return { aminos: aminos, images: images };
};
